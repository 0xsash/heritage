"""
BELFORT - tree impostor atlas pipeline (Blender 4.2 LTS, headless, Cycles CPU).

    blender -b --factory-startup --python tools/blender/make_trees.py -- \
        --work <scratch dir> [--out public/textures/trees] [--only oak,willow] \
        [--no-render] [--samples 64]

Look: stylised / painterly. Crowns are built from clustered, gently lumpy foliage masses
("clumps") that are painted light on top and dark underneath; trunks and boughs are smooth,
slightly exaggerated tubes with painted bark. Everything is generated by this script - there
are no downloaded models or textures.

What it does
  1. Grows five procedural trees: oak, poplar, pollard willow, Scots pine, apple.
  2. Renders each tree orthographically from azimuth 0 and 90 degrees, twice:
       albedo  = unlit painted base colour x soft ambient occlusion, straight alpha
       normal  = billboard-frame normal (X right, Y up, Z to camera): rounded clump normals
                 blended with the normal of an ellipsoid fitted to the crown, n*0.5+0.5
  3. Packs a 2 x 5 grid of 512 px cells (1024 x 2560), bleeds RGB into the transparent area
     (alpha untouched) and writes trees_albedo.png, trees_normal.png and trees.json.

Per-cell renders are cached in <work>/render so single species can be re-done with --only.
"""
