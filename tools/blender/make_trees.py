def render_species(name, H, W, a):
    t0 = time.time()
    sc = reset_scene()
    sc.cycles.samples = a["samples"]
    gen, seed = GENERATORS[name]
    tr = Tree(name, seed, max(H, W) * 1.03 / CELL)
    gen(tr)
    wV, wCOL, wQ = build_wood(tr)
    fV, fT, fQ, TL, TC, TONE, CN = build_foliage(tr)
    fruit = build_fruit(tr)
    # ---- normalise to the target height / width (trunk base stays on the cell centre line)
    s = H / max(fV[:, 2].max(), wV[:, 2].max())
    wx = (fV[:, 0].max() - fV[:, 0].min()) * s
    wy = (fV[:, 1].max() - fV[:, 1].min()) * s
    f = float(np.clip(W / (0.5 * (wx + wy)), 0.8, 1.25))
    S = np.array([s * f, s * f, s])
    wV = wV * S
    fV = fV * S
    if fruit is not None:
        fruit = (fruit[0] * S, fruit[1], fruit[2])
    allv = np.vstack([wV, fV])
    top = float(allv[:, 2].max())
    half = float(np.abs(allv[:, :2]).max())
    quad = math.ceil(max(top, 2 * half) * 1.03 * 20) / 20.0
    width = 0.5 * float((fV[:, 0].max() - fV[:, 0].min()) + (fV[:, 1].max() - fV[:, 1].min()))
    lo, hi = fV.min(axis=0), fV.max(axis=0)
    ell_c = tuple(0.5 * (lo + hi))
    ell_r = tuple(np.maximum(0.5 * (hi - lo), 0.3))
    fCOL = paint_foliage(tr, fV, TL, TC, TONE, ell_c, ell_r)

    wood = new_mesh(name + "_wood", wV, quads=wQ)
    set_col(wood, wCOL)
    leaves = new_mesh(name + "_foliage", fV, tris=fT, quads=fQ)
    set_col(leaves, fCOL)
    set_vec(leaves, "cn", CN)
    meshes = [wood, leaves]
    if fruit is not None:
        fm = new_mesh(name + "_fruit", fruit[0], tris=fruit[2])
        set_col(fm, fruit[1])
        set_vec(fm, "cn", unit_rows(fruit[0] - np.asarray(ell_c)))
        meshes.append(fm)
    objs = []
    for me in meshes:
        ob = bpy.data.objects.new(me.name, me)
        sc.collection.objects.link(ob)
        objs.append(ob)
    cam = bpy.data.cameras.new("cam")
    cam.type = "ORTHO"
    cam.ortho_scale = quad
    cam.clip_start = 0.1
    cam.clip_end = 400
    cob = bpy.data.objects.new("cam", cam)
    sc.collection.objects.link(cob)
    sc.camera = cob
    px = quad / CELL
    print("[%s] %d tubes, %d clumps, %d plumes, %d foliage verts | H %.2f W %.2f quad %.2f | gen %.1fs" % (
        name, len(tr.tubes), len(tr.clumps), len(tr.plumes), len(fV), top, width, quad, time.time() - t0))
    for vi, (right, up, back, eul) in enumerate(VIEW_AXES):
        cob.location = (back[0] * 100.0, back[1] * 100.0, quad / 2.0)
        cob.rotation_euler = eul
        for mode in ("albedo", "normal"):
            axes = (right, up, back)
            mb = make_material("bark_" + mode, mode, "bark", axes, ell_c, ell_r, 0.09 * top, 7 * px)
            ml = make_material("leaf_" + mode, mode, "leaf", axes, ell_c, ell_r, 0.11 * top, 7 * px, tr.pal)
            mf = make_material("fruit_" + mode, mode, "fruit" if mode == "albedo" else "leaf", axes,
                               ell_c, ell_r, 0.05 * top, 7 * px)
            for ob in objs:
                ob.data.materials.clear()
                ob.data.materials.append(mb if ob.data is wood else ml if ob.data is leaves else mf)
            sc.view_settings.view_transform = "Standard" if mode == "albedo" else "Raw"
            sc.render.filepath = os.path.join(a["render"], "%s_%d_%s.png" % (name, vi, mode))
            t1 = time.time()
            bpy.ops.render.render(write_still=True)
            print("[%s] view %d %s rendered in %.1fs" % (name, vi, mode, time.time() - t1))
    meta = {"name": name, "height": round(top, 2), "width": round(width, 2),
            "quadHeight": round(quad, 2), "quadWidth": round(quad, 2)}
    with open(os.path.join(a["render"], name + ".json"), "w") as fh:
        json.dump(meta, fh)
    return meta


