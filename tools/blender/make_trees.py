class NB:
    """Tiny node-graph builder."""

    def __init__(self, name):
        self.mat = bpy.data.materials.new(name)
        self.mat.use_nodes = True
        self.nt = self.mat.node_tree
        self.nt.nodes.clear()

    def node(self, typ, **props):
        n = self.nt.nodes.new(typ)
        for k, v in props.items():
            setattr(n, k, v)
        return n

    def link(self, a, b):
        self.nt.links.new(a, b)

    def vmath(self, op, a, b=None):
        n = self.node("ShaderNodeVectorMath", operation=op)
        for i, x in enumerate((a, b)):
            if x is None:
                continue
            if hasattr(x, "links"):
                self.link(x, n.inputs[i])
            else:
                n.inputs[i].default_value = tuple(x)
        return n.outputs["Value"] if op in ("DOT_PRODUCT", "LENGTH") else n.outputs["Vector"]

    def vscale(self, vec, k):
        n = self.node("ShaderNodeVectorMath", operation="SCALE")
        self.link(vec, n.inputs[0])
        if hasattr(k, "links"):
            self.link(k, n.inputs["Scale"])
        else:
            n.inputs["Scale"].default_value = float(k)
        return n.outputs["Vector"]

    def math(self, op, a, b=None, clamp=False):
        n = self.node("ShaderNodeMath", operation=op, use_clamp=clamp)
        for i, x in enumerate((a, b)):
            if x is None:
                continue
            if hasattr(x, "links"):
                self.link(x, n.inputs[i])
            else:
                n.inputs[i].default_value = float(x)
        return n.outputs[0]

    def emit(self, color_socket):
        e = self.node("ShaderNodeEmission")
        self.link(color_socket, e.inputs["Color"])
        o = self.node("ShaderNodeOutputMaterial")
        self.link(e.outputs[0], o.inputs["Surface"])


def to_cam(nb, vec, axes, zmode):
    right, up, back = axes
    x = nb.vmath("DOT_PRODUCT", vec, right)
    y = nb.vmath("DOT_PRODUCT", vec, up)
    z = nb.vmath("DOT_PRODUCT", vec, back)
    z = nb.math("ABSOLUTE", z) if zmode == "abs" else nb.math("MAXIMUM", z, 0.12)
    c = nb.node("ShaderNodeCombineXYZ")
    nb.link(x, c.inputs[0]); nb.link(y, c.inputs[1]); nb.link(z, c.inputs[2])
    return c.outputs[0]


def make_material(name, mode, kind, axes, ell_c, ell_r, ao_dist, dab, pal=None):
    """mode: 'albedo' | 'normal';  kind: 'leaf' | 'bark' | 'fruit'."""
    nb = NB(name)
    geo = nb.node("ShaderNodeNewGeometry")
    if mode == "albedo":
        col = nb.node("ShaderNodeAttribute", attribute_name="Col").outputs["Color"]
        ao = nb.node("ShaderNodeAmbientOcclusion", samples=8)
        ao.inputs["Distance"].default_value = ao_dist
        a = nb.math("POWER", ao.outputs["AO"], 1.1, clamp=True)
        a = nb.math("ADD", nb.math("MULTIPLY", a, 1.0 - AO_MIN), AO_MIN)
        if kind == "leaf":
            # painted foliage: the tone parameter is jittered per brush dab (soft cellular
            # pattern, a few pixels across) and mapped through a five-tone ramp with soft steps
            vor = nb.node("ShaderNodeTexVoronoi", feature="SMOOTH_F1")
            vor.inputs["Scale"].default_value = 1.0 / dab
            vor.inputs["Smoothness"].default_value = 0.5
            nb.link(geo.outputs["Position"], vor.inputs["Vector"])
            sep = nb.node("ShaderNodeSeparateColor")
            nb.link(vor.outputs["Color"], sep.inputs["Color"])
            tsep = nb.node("ShaderNodeSeparateColor")
            nb.link(col, tsep.inputs["Color"])
            t = nb.math("ADD", tsep.outputs[0], nb.math("MULTIPLY", nb.math("SUBTRACT", sep.outputs[0], 0.5), 0.2))
            ramp = nb.node("ShaderNodeValToRGB")
            nb.link(t, ramp.inputs["Fac"])
            dark, mid, light = pal
            tones = [dark * 0.82, dark * 0.5 + mid * 0.5, mid, mid * 0.5 + light * 0.5, light]
            stops = [(0.0, 0)]
            for i, edge in enumerate((0.3, 0.46, 0.62, 0.78)):
                stops += [(edge - 0.035, i), (edge + 0.035, i + 1)]
            stops.append((1.0, 4))
            cr = ramp.color_ramp
            cr.interpolation = "LINEAR"
            while len(cr.elements) < len(stops):
                cr.elements.new(0.5)
            for el, (pos, ti) in zip(cr.elements, stops):
                el.position = pos
                el.color = (*tones[ti], 1.0)
            col = ramp.outputs["Color"]
        nb.emit(nb.vscale(col, a))
    else:
        if kind == "leaf":
            d = nb.vmath("SUBTRACT", geo.outputs["Position"], ell_c)
            ell = nb.vmath("NORMALIZE", nb.vmath("MULTIPLY", d, [1.0 / (r * r) for r in ell_r]))
            cn = nb.node("ShaderNodeAttribute", attribute_name="cn").outputs["Vector"]
            n = nb.vmath("ADD", nb.vscale(to_cam(nb, cn, axes, "max"), 0.55),
                         nb.vscale(to_cam(nb, ell, axes, "abs"), 0.45))
        else:
            n = to_cam(nb, geo.outputs["Normal"], axes, "abs")
        n = nb.vmath("NORMALIZE", n)
        nb.emit(nb.vmath("ADD", nb.vscale(n, 0.5), (0.5, 0.5, 0.5)))
    return nb.mat


