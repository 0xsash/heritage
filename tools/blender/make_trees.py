# --------------------------------------------------------------------------- utils
def srgb2lin(c):
    c = np.asarray(c, dtype=np.float64) / 255.0
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def unit(v):
    return v / (np.linalg.norm(v) + 1e-12)


def unit_rows(a):
    return a / (np.linalg.norm(a, axis=-1, keepdims=True) + 1e-12)


def perp(v):
    a = np.array([0.0, 0.0, 1.0]) if abs(v[2]) < 0.9 else np.array([1.0, 0.0, 0.0])
    return unit(np.cross(v, a))


def rot_about(v, axis, ang):
    c, s = math.cos(ang), math.sin(ang)
    return v * c + np.cross(axis, v) * s + axis * np.dot(axis, v) * (1 - c)


def smooth(x, a, b):
    t = np.clip((x - a) / (b - a), 0.0, 1.0)
    return t * t * (3 - 2 * t)


def frame_for(axis):
    """Rows = local x, y, z in world space, local z along `axis`."""
    z = unit(np.asarray(axis, float))
    x = perp(z)
    return np.array([x, np.cross(z, x), z])


def lump(P, seed, freq):
    """Cheap smooth 3D noise (sum of sines) in about [-1, 1]; vectorised."""
    rs = np.random.default_rng(int(seed))
    out = np.zeros(P.shape[:-1])
    for _ in range(5):
        k = unit(rs.normal(size=3)) * freq * rs.uniform(0.7, 1.4)
        out += np.sin(P @ k + rs.uniform(0, 6.28)) * rs.uniform(0.6, 1.0)
    return out / 2.6


def make_env(c, r, bump=0.2, freq=1.6, seed=0.0):
    """Bumpy ellipsoid crown envelope that limits how far boughs reach."""
    c = np.asarray(c, float)
    r = np.asarray(r, float)

    def inside(p):
        q = (p - c) / r
        d = float(np.linalg.norm(q))
        if d < 1e-6:
            return True
        n = q / d
        b = mnoise.noise(Vector((n[0] * freq + seed, n[1] * freq - seed, n[2] * freq + 2.7 * seed)))
        return d < 1.0 + bump * 2.0 * b
    return inside


_ICO = {}


def icosphere(n):
    if n in _ICO:
        return _ICO[n]
    t = (1 + 5 ** 0.5) / 2
    V = np.array([(-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0), (0, -1, t), (0, 1, t),
                  (0, -1, -t), (0, 1, -t), (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1)], float)
    V = unit_rows(V)
    F = np.array([(0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11), (1, 5, 9), (5, 11, 4),
                  (11, 10, 2), (10, 7, 6), (7, 1, 8), (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8),
                  (3, 8, 9), (4, 9, 5), (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1)])
    for _ in range(n):
        e = np.concatenate([F[:, [0, 1]], F[:, [1, 2]], F[:, [2, 0]]])
        e.sort(axis=1)
        ue, inv = np.unique(e, axis=0, return_inverse=True)
        mid = unit_rows(V[ue[:, 0]] + V[ue[:, 1]])
        mi = len(V) + inv.reshape(-1).reshape(3, -1)
        V = np.vstack([V, mid])
        a, b, c = F[:, 0], F[:, 1], F[:, 2]
        ab, bc, ca = mi[0], mi[1], mi[2]
        F = np.concatenate([np.stack([a, ab, ca], 1), np.stack([b, bc, ab], 1),
                            np.stack([c, ca, bc], 1), np.stack([ab, bc, ca], 1)])
    _ICO[n] = (V, F)
    return V, F


# --------------------------------------------------------------------------- tree data
class Tree:
    def __init__(self, name, seed, px):
        self.name = name
        self.seed = seed
        self.rng = np.random.default_rng(seed)
        self.px = px                # approx. metres per atlas pixel (for tessellation decisions)
        self.rmin = 1.0 * px        # thinnest branch: 2 px across, so nothing shimmers
        self.tubes = []             # wood: (pts, radii, prof, paint)
        self.tips = []              # (pts, radii, level) of every branch grown
        self.clumps = []            # foliage masses
        self.plumes = []            # elongated foliage (pts, radii, tone)
        self.fruit = []             # (pos, r, col)
        self.pal = None             # (dark, mid, light) linear rgb
        self.levels = []
        self.env = None
        self.env_levels = 99

    # ---- wood ---------------------------------------------------------------------
    def path(self, start, d, length, seg, wobble=0.0, trop=0.0):
        rng = self.rng
        nseg = max(3, int(math.ceil(length / seg)))
        step = length / nseg
        pts = np.empty((nseg + 1, 3))
        pts[0] = start
        d = unit(np.asarray(d, float))
        wob = wobble * math.sqrt(step)
        bend = rng.normal(size=3)
        for i in range(nseg):
            t = (i + 1) / nseg
            bend = unit(bend * 0.65 + rng.normal(size=3) * 0.55)
            d = d + bend * wob
            d[2] += (trop(t) if callable(trop) else trop) * step
            d = unit(d)
            pts[i + 1] = pts[i] + d * step
        return pts

    def grow(self, start, d, length, r0, level):
        lp = self.levels[level]
        pts = self.path(start, d, length, lp["seg"], lp.get("wobble", 0.0), lp.get("trop", 0.0))
        t = np.linspace(0.0, 1.0, len(pts))
        if "rfun" in lp:
            radii = r0 * lp["rfun"](t)
        else:
            radii = np.maximum(r0 * (1.0 - (1.0 - lp.get("tip", 0.3)) * t ** lp.get("tpow", 1.0)), self.rmin)
        self.tubes.append((pts, radii, lp.get("prof"), lp["paint"]))
        self.tips.append((pts, radii, level))
        if level + 1 < len(self.levels) and lp.get("n", 0) > 0:
            self.spawn(pts, radii, level)
        return pts, radii

    def spawn(self, pts, radii, level):
        lp = self.levels[level]
        cp = self.levels[level + 1]
        rng = self.rng
        n = lp["n"]
        t0, t1 = lp.get("t0", 0.2), lp.get("t1", 1.0)
        az = rng.uniform(0, 2 * math.pi)
        m = len(pts) - 1
        for k in range(n):
            az += 2.39996 + rng.normal(0, 0.4)
            if rng.random() < lp.get("prune", 0.0):
                continue
            u = (k + rng.uniform(0.15, 0.85)) / n
            f = (t0 + (t1 - t0) * u) * m
            i = min(int(f), m - 1)
            fr = f - i
            p = pts[i] * (1 - fr) + pts[i + 1] * fr
            d = unit(pts[i + 1] - pts[i])
            rp = radii[i] * (1 - fr) + radii[i + 1] * fr
            ang = lp.get("ang", 45.0)
            ang = ang(u) if callable(ang) else ang
            a = math.radians(ang + lp.get("angvar", 12.0) * rng.normal())
            side = rot_about(perp(d), d, az)
            cdir = d * math.cos(a) + side * math.sin(a)
            lo, hi = cp["len"]
            clen = rng.uniform(lo, hi)
            if "shape" in cp:
                clen *= cp["shape"](u)
            if self.env is not None and level + 1 <= self.env_levels:
                clen = self.clip_len(p, cdir, clen)
            if clen < cp.get("minlen", 0.6 * lo):
                continue
            cr = min(rp * 0.9, rp * lp.get("rr", 0.55) * rng.uniform(0.9, 1.1))
            self.grow(p, cdir, clen, cr, level + 1)

    def clip_len(self, p, d, clen):
        stp = max(0.05, clen / 14.0)
        dist = 0.0
        while dist < clen:
            if not self.env(p + d * (dist + stp)):
                break
            dist += stp
        return min(clen, dist + stp * self.rng.uniform(0.0, 1.0))

    def reach_len(self, p, d, maxlen, minlen):
        """Longest length <= maxlen whose end point is still inside the envelope."""
        ln = maxlen
        while ln > minlen:
            if self.env(p + d * ln):
                return ln
            ln -= 0.1 * maxlen
        return minlen

    # ---- foliage ------------------------------------------------------------------
    def clump(self, c, R, axis=(0, 0, 1), sat=8, tone=0.0, sat_size=(0.42, 0.56), sat_out=0.72, sub=7):
        R = np.asarray(R, float) * np.ones(3)
        self.clumps.append(dict(c=np.asarray(c, float), R=R, axes=frame_for(axis), sat=sat, tone=tone,
                                sat_size=sat_size, sat_out=sat_out, sub=sub,
                                seed=int(self.rng.integers(1 << 30))))


def shell_clumps(tr, c, R, n, r_range, zmin=-0.5, squash=0.82, jitter=0.1, **kw):
    """Clumps spread over the upper part of an ellipsoid shell -> one broad, lumpy dome."""
    rng = tr.rng
    c = np.asarray(c, float)
    R = np.asarray(R, float)
    total = int(math.ceil(n / ((1.0 - zmin) / 2.0)))
    rot = rng.uniform(0, 6.28)
    out = []
    for j in range(total):
        d = fib_dir(j, total)
        if d[2] < zmin:
            continue
        d = np.array([d[0] * math.cos(rot) - d[1] * math.sin(rot), d[0] * math.sin(rot) + d[1] * math.cos(rot), d[2]])
        d = unit(d + rng.normal(0, jitter, 3))
        r = rng.uniform(*r_range) * (1.08 - 0.16 * max(d[2], 0.0))
        pos = c + d * R * rng.uniform(0.92, 1.04)
        tr.clump(pos, (r, r, squash * r), tone=rng.normal(0, 0.05), **kw)
        out.append((pos, r))
    return out


def limb_to(tr, start, target, r0, level=1):
    """Grow a wobbly bough from start that is bent to end exactly at target."""
    d = target - start
    pts, radii = tr.grow(start, unit(d), float(np.linalg.norm(d)), r0, level)
    t = np.linspace(0.0, 1.0, len(pts))[:, None]
    pts += (target - pts[-1]) * t ** 1.5              # in place: the tube list holds this array
    return pts, radii


# --------------------------------------------------------------------------- painted bark
def bark(base=(0, 0, 0), streak=0.08, nstreak=7, twist=0.0, ph=0.0, grad=None):
    """Painted bark: flat colour, soft lengthwise streaks, lighter top side / darker underside."""
    base = srgb2lin(base)

    def paint(th, s, nz, z):
        col = base if grad is None else grad(z)                 # (3,) or (m, k+1, 3)
        st = 1.0 + streak * np.sin(nstreak * th + twist * s + ph) * (0.6 + 0.4 * np.sin(1.7 * s + 2 * th))
        light = 0.84 + 0.24 * (0.5 + 0.5 * nz)
        return col * (st * light)[:, :, None]
    return paint


def root_flare(n_ridges, strength, reach, phase, twist=0.8, knob=0.05, ridge=0.0):
    """Radius multiplier: buttress roots at the base, optional spiral ridges all the way up."""
    def prof(th, s, t):
        fl = strength * np.exp(-np.maximum(s, 0) / reach)
        c = np.cos(n_ridges * th + twist * s + phase)
        ridges = (0.5 + 0.5 * c) ** 1.6
        gn = knob * (np.sin(3 * th + 2.3 * s + phase) + 0.6 * np.sin(5 * th - 3.1 * s))
        return 1.0 + fl * (0.3 + 0.9 * ridges) + ridge * c + gn
    return prof


def palette(dark, mid, light):
    return (srgb2lin(dark), srgb2lin(mid), srgb2lin(light))


