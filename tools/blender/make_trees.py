def parse_args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.dirname(os.path.dirname(here))
    a = {"work": os.path.join(os.environ.get("TMPDIR", "/tmp"), "belfort-trees"),
         "out": os.path.join(repo, "public", "textures", "trees"), "only": None,
         "do_render": True, "samples": 64}
    i = 0
    while i < len(argv):
        k = argv[i]
        if k == "--no-render":
            a["do_render"] = False
        elif k in ("--work", "--out", "--only", "--samples"):
            i += 1
            a[k[2:]] = argv[i]
        else:
            raise SystemExit("unknown argument " + k)
        i += 1
    a["samples"] = int(a["samples"])
    a["render"] = os.path.join(a["work"], "render")
    os.makedirs(a["render"], exist_ok=True)
    return a


def main():
    a = parse_args()
    only = a["only"].split(",") if a["only"] else [s[0] for s in SPECIES]
    if a["do_render"]:
        for name, H, W in SPECIES:
            if name in only:
                render_species(name, H, W, a)
    missing = [s[0] for s in SPECIES if not os.path.exists(os.path.join(a["render"], s[0] + ".json"))]
    if missing:
        print("not assembling atlas yet; species not rendered:", missing)
        return
    assemble(a)


if __name__ == "__main__":
    main()
