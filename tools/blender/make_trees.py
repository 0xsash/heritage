def gen_oak(tr):
    """Oak: massive twisted bole, bold sinuous boughs, broad dome of big rounded clumps."""
    rng = tr.rng
    tr.pal = palette((44, 60, 34), (90, 106, 46), (160, 156, 76))
    bk = dict(base=(112, 94, 72))

    def rfun(t):
        r = np.where(t < 0.82, 1.0 - 0.24 * t / 0.82, 0.0)
        r = np.where(t >= 0.82, 0.76 * np.sqrt(np.maximum(0.0, 1 - ((t - 0.82) / 0.18) ** 2)) + 0.01, r)
        return r

    tr.levels = [
        dict(seg=0.25, wobble=0.1, rfun=rfun,
             prof=root_flare(5, 0.7, 0.7, 0.6, twist=1.0, knob=0.05, ridge=0.11),
             paint=bark(streak=0.13, nstreak=5, twist=1.0, ph=0.6, **bk)),
        dict(seg=0.45, wobble=0.2, trop=lambda t: -0.05 + 0.1 * t, tip=0.4, tpow=0.9,
             paint=bark(streak=0.07, **bk)),
    ]
    lean = unit(np.array([0.05, 0.02, 1.0]))
    pts, radii = tr.grow(np.array([0.0, 0.0, -0.2]), lean, 5.9, 0.98, 0)
    top = pts[-1]
    shell = shell_clumps(tr, (0.2, 0.1, 10.6), (5.4, 5.4, 4.6), 34, (1.75, 2.3), zmin=-0.66, squash=0.8)
    for k in range(5):   # dark heart of the crown, so the few gaps look into shade, not sky
        a = k * 2.39996
        tr.clump((1.2 * math.cos(a), 1.2 * math.sin(a), 10.8 + 1.3 * math.sin(1.7 * k)), (2.8, 2.8, 2.3),
                 sat=4, tone=-0.16, sub=0)
    # bold boughs from the head of the bole into the lower and middle clumps
    order = sorted(range(len(shell)), key=lambda i: shell[i][0][2])
    for n_, i in enumerate(order[:11] + order[14:18:2]):
        pos, r = shell[i]
        radial = unit(np.array([pos[0], pos[1], 0.0]))
        start = top - lean * rng.uniform(0.3, 1.6) + radial * 0.25
        limb_to(tr, start, pos, 0.98 * rng.uniform(0.32, 0.44))


def gen_poplar(tr):
    """Poplar: tall straight stem, narrow flame-shaped column of upward-sweeping clumps."""
    rng = tr.rng
    tr.pal = palette((62, 84, 42), (118, 136, 58), (178, 184, 96))
    bk = dict(base=(140, 132, 106))
    tr.levels = [
        dict(seg=0.8, wobble=0.012, tip=0.12, prof=root_flare(4, 0.4, 0.6, 1.0, knob=0.02),
             paint=bark(streak=0.07, nstreak=6, **bk)),
        dict(seg=0.4, wobble=0.1, trop=0.22, tip=0.4, paint=bark(streak=0.04, **bk)),
    ]
    up = np.array([0.0, 0.0, 1.0])
    tr.grow(np.array([0.0, 0.0, -0.2]), np.array([0.01, 0.0, 1.0]), 24.0, 0.6, 0)
    n = 30
    az0 = rng.uniform(0, 6.28)
    for i in range(n):
        u = (i + 0.5) / n
        h = 7.6 + 15.4 * u
        w = 3.0 * math.sin(math.pi * (0.14 + 0.74 * u)) ** 0.6 + 0.2          # widest in the middle, round top
        az = az0 + i * 2.39996 + rng.normal(0, 0.25)
        radial = np.array([math.cos(az), math.sin(az), 0.0])
        ra = 0.5 * w + 0.35
        c = radial * (0.5 * w * rng.uniform(0.85, 1.12)) + up * h
        tr.clump(c, (ra, ra, rng.uniform(1.9, 2.5)), axis=radial * 0.22 + up,
                 sat=7, tone=rng.normal(0, 0.06), sat_size=(0.4, 0.52))
    tr.clump((0, 0, 23.6), (1.5, 1.5, 2.0), sat=6, tone=0.04)         # rounded top
    for k in range(5):                                                # dark core up the stem
        tr.clump((0, 0, 9.0 + 3.0 * k), (1.5, 1.5, 2.4), sat=3, tone=-0.14, sub=0)
    for k in range(7):                                                # boughs visible under the crown
        az = az0 + 1.0 + k * 2.39996
        d = np.array([math.cos(az) * 0.6, math.sin(az) * 0.6, 0.8])
        tr.grow(np.array([0.0, 0.0, 4.4 + 0.45 * k]), d, rng.uniform(2.8, 3.8), 0.17, 1)


def gen_willow(tr):
    """Pollard willow (knotwilg): squat knobbly bole, swollen head, burst of leafy shoots."""
    rng = tr.rng
    tr.pal = palette((70, 88, 60), (116, 136, 88), (162, 176, 116))
    bk = dict(base=(104, 90, 66))

    def rfun(t):
        r = np.where(t < 0.5, 1.0 - 0.2 * t / 0.5, 0.0)
        r = np.where((t >= 0.5) & (t < 0.84), 0.8 + 0.62 * np.sin((t - 0.5) / 0.34 * math.pi / 2) ** 1.5, r)
        r = np.where(t >= 0.84, 1.42 * np.sqrt(np.maximum(0.0, 1 - ((t - 0.84) / 0.16) ** 2)) + 0.01, r)
        return r

    fl = root_flare(5, 0.5, 0.25, 2.0, twist=1.5, knob=0.07, ridge=0.05)

    def prof(th, s, t):
        knobs = 0.12 * np.sin(4 * th + 9 * t) * np.sin(10 * t) + 0.07 * np.sin(6 * th - 12 * t)
        return fl(th, s, t) + knobs * (0.3 + t)

    tr.levels = [dict(seg=0.1, wobble=0.07, rfun=rfun, prof=prof,
                      paint=bark(streak=0.14, nstreak=5, twist=1.5, ph=2.0, **bk))]
    lean = unit(np.array([0.07, -0.03, 1.0]))
    pts, radii = tr.grow(np.array([0.0, 0.0, -0.08]), lean, 2.7, 0.4, 0)
    m = len(pts) - 1
    nshoot = 110
    az0 = rng.uniform(0, 6.28)
    shoot_paint = bark((128, 118, 76), streak=0.03)
    for k in range(nshoot):
        az = az0 + k * 2.39996 + rng.normal(0, 0.25)
        u = (k + 0.5) / nshoot
        phi = math.radians(2 + 60 * u ** 0.72 + rng.normal(0, 4))
        f = (0.97 - 0.2 * u) * m
        i = min(int(f), m - 1)
        p0 = pts[i] + (pts[i + 1] - pts[i]) * (f - i)
        rr = np.interp(f, np.arange(m + 1), radii)
        radial = np.array([math.cos(az), math.sin(az), 0.0])
        d = radial * math.sin(phi) + lean * math.cos(phi)
        ln = rng.uniform(3.3, 4.6) * (1.0 - 0.2 * u) * (1.0 + 0.08 * math.sin(2.0 * az + 1.0))
        sp = tr.path(p0 + radial * rr * 0.6, d, ln, 0.08, 0.04, lambda t, u=u: 0.06 - 0.95 * t * t * (0.12 + u))
        t = np.linspace(0, 1, len(sp))
        ns = int(0.3 * len(sp))                         # bare stem below the leafy part
        tr.tubes.append((sp[:ns], np.full(ns, max(rng.uniform(0.04, 0.055), tr.rmin)), None, shoot_paint))
        rmax = rng.uniform(0.22, 0.31)
        g = (smooth(t, 0.1, 0.42) * (1.0 - 0.5 * smooth(t, 0.48, 1.0)) *
             np.sqrt(np.clip(1.0 - np.clip((t - 0.93) / 0.07, 0, 1) ** 2, 0, 1)))       # lance-shaped, round tip
        j0 = int(0.1 * len(sp))
        tr.plumes.append((sp[j0:], np.maximum(rmax * g[j0:], 0.003), rng.normal(0, 0.05) - 0.08 * (1 - u)))
    head = pts[-1]
    tr.clump(head + np.array([0, 0, 1.4]), (1.5, 1.5, 1.4), sat=5, tone=-0.2, sub=0)   # body of the mop


def gen_pine(tr):
    """Scots pine: tall bare orange-brown stem, bold crooked branches, flat cloud-like pads."""
    rng = tr.rng
    tr.pal = palette((30, 46, 38), (62, 84, 54), (118, 132, 78))
    grey = srgb2lin((112, 92, 78))
    orange = srgb2lin((196, 118, 70))

    def grad(z):
        k = smooth(z, 4.0, 11.0)[..., None]
        return grey * (1 - k) + orange * k

    tr.levels = [
        dict(seg=0.6, wobble=0.045, rfun=lambda t: 1.0 - 0.7 * t ** 1.25,
             prof=root_flare(4, 0.35, 0.5, 0.3, knob=0.025), paint=bark(streak=0.09, nstreak=6, grad=grad)),
        dict(seg=0.3, wobble=0.2, trop=lambda t: -0.02 + 0.3 * t, tip=0.42,
             paint=bark(streak=0.05, grad=grad), n=2, t0=0.4, t1=0.85, ang=58, angvar=12, rr=0.7),
        dict(len=(1.0, 1.8), seg=0.25, wobble=0.2, trop=0.2, tip=0.5, paint=bark(streak=0.04, grad=grad)),
    ]
    pts, radii = tr.grow(np.array([0.0, 0.0, -0.2]), np.array([0.03, 0.01, 1.0]), 19.0, 0.42, 0)
    m = len(pts) - 1
    nb = 10
    az0 = rng.uniform(0, 6.28)
    for k in range(nb):
        u = (k + rng.uniform(0.2, 0.8)) / nb
        f = (0.57 + 0.38 * u) * m
        i = min(int(f), m - 1)
        p = pts[i] + (pts[i + 1] - pts[i]) * (f - i)
        az = az0 + k * 2.39996 + rng.normal(0, 0.3)
        phi = math.radians(86 - 38 * u + rng.normal(0, 6))
        d = np.array([math.cos(az) * math.sin(phi), math.sin(az) * math.sin(phi), math.cos(phi)])
        tr.grow(p, d, rng.uniform(1.9, 3.1) * (1.0 - 0.3 * u), max(0.09, radii[i] * 0.5), 1)
    for pts_, radii_, level in list(tr.tips):
        if level == 1:
            r = rng.uniform(1.5, 2.0)
        elif level == 2:
            r = rng.uniform(1.1, 1.5)
        else:
            continue
        tr.clump(pts_[-1] + np.array([0, 0, 0.25 * r]), (r, r, 0.52 * r), sat=7, tone=rng.normal(0, 0.05),
                 sat_size=(0.4, 0.55), sat_out=0.78)
    tr.clump(pts[-1] - np.array([0, 0, 0.5]), (1.7, 1.7, 1.15), sat=7, tone=0.03)
    # a few bold dead stubs on the bare stem
    tr.levels = [dict(seg=0.25, wobble=0.2, trop=-0.06, tip=0.5, paint=bark((92, 78, 68), streak=0.04))]
    for k in range(3):
        f = (0.3 + 0.08 * k + rng.uniform(0, 0.04)) * m
        i = int(f)
        az = rng.uniform(0, 6.28)
        d = np.array([math.cos(az), math.sin(az), rng.uniform(0.0, 0.3)])
        tr.grow(pts[i], d, rng.uniform(0.7, 1.3), 0.07, 0)


def gen_apple(tr):
    """Orchard apple: short stout leaning bole, spreading limbs, small round crown, red fruit."""
    rng = tr.rng
    tr.pal = palette((40, 66, 32), (84, 120, 46), (158, 172, 74))
    bk = dict(base=(118, 100, 84))

    def rfun(t):
        r = np.where(t < 0.8, 1.0 - 0.2 * t / 0.8, 0.0)
        r = np.where(t >= 0.8, 0.8 * np.sqrt(np.maximum(0.0, 1 - ((t - 0.8) / 0.2) ** 2)) + 0.01, r)
        return r

    tr.levels = [
        dict(seg=0.1, wobble=0.12, rfun=rfun, prof=root_flare(4, 0.45, 0.16, 0.9, twist=3.0, knob=0.05, ridge=0.06),
             paint=bark(streak=0.1, nstreak=4, twist=3.0, ph=0.9, **bk)),
        dict(seg=0.16, wobble=0.18, trop=lambda t: -0.1 + 0.2 * t, tip=0.45, paint=bark(streak=0.05, **bk)),
    ]
    lean = unit(np.array([-0.05, 0.03, 1.0]))
    pts, radii = tr.grow(np.array([0.0, 0.0, -0.06]), lean, 1.7, 0.22, 0)
    top = pts[-1]
    shell = shell_clumps(tr, (0.0, 0.0, 3.2), (1.5, 1.5, 1.2), 16, (0.6, 0.8), zmin=-0.62, squash=0.86)
    tr.clump((0, 0, 3.2), (1.15, 1.15, 0.9), sat=4, tone=-0.16, sub=0)
    order = sorted(range(len(shell)), key=lambda i: shell[i][0][2])
    for i in order[:7]:
        pos, r = shell[i]
        radial = unit(np.array([pos[0], pos[1], 0.0]))
        limb_to(tr, top - lean * rng.uniform(0.08, 0.4) + radial * 0.05, pos, 0.22 * rng.uniform(0.38, 0.5))
    reds = [srgb2lin(c) for c in ((176, 52, 40), (196, 84, 46), (204, 150, 60), (160, 40, 40))]
    for k in range(30):
        pos, r = shell[int(rng.integers(len(shell)))]
        d = unit(np.array([rng.normal(), rng.normal(), rng.uniform(-0.75, 0.3)]))
        tr.fruit.append((pos + d * r * np.array([1.05, 1.05, 0.88]), rng.uniform(0.05, 0.062),
                         reds[int(rng.integers(len(reds)))]))


