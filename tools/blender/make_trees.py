def tube_rings(pts, radii, k, prof=None):
    m = len(pts)
    seg = pts[1:] - pts[:-1]
    sl = np.linalg.norm(seg, axis=1)
    T = seg / sl[:, None]
    tang = np.vstack([T[0], unit_rows(T[:-1] + T[1:]), T[-1]])
    s = np.concatenate([[0.0], np.cumsum(sl)])
    N = np.empty((m, 3))
    n = perp(tang[0])
    for i in range(m):
        n = unit(n - tang[i] * np.dot(n, tang[i]))
        N[i] = n
    B = np.cross(tang, N)
    th = np.linspace(0, 2 * math.pi, k + 1)
    mult = np.ones((m, k + 1))
    if prof is not None:
        mult = prof(th[None, :], s[:, None], (s / s[-1])[:, None]) * mult
    radial = np.cos(th)[None, :, None] * N[:, None, :] + np.sin(th)[None, :, None] * B[:, None, :]
    ring = pts[:, None, :] + (radii[:, None] * mult)[:, :, None] * radial
    i_ = np.arange(m - 1)[:, None] * (k + 1)
    j_ = np.arange(k)[None, :]
    a = i_ + j_
    quads = np.stack([a, a + 1, a + k + 2, a + k + 1], axis=2).reshape(-1, 4)
    return ring, radial, th, s, quads


def sides_for(r, px):
    q = r / px
    return 44 if q > 12 else 28 if q > 5 else 16 if q > 2 else 10


def build_wood(tr):
    V, COL, Q = [], [], []
    off = 0
    for pts, radii, prof, paint in tr.tubes:
        k = sides_for(float(radii.max()), tr.px)
        ring, radial, th, s, quads = tube_rings(pts, radii, k, prof)
        nz = radial[:, :, 2]
        z = np.broadcast_to(pts[:, 2][:, None], nz.shape)
        col = paint(th[None, :], s[:, None], nz, z)
        V.append(ring.reshape(-1, 3)); COL.append(col.reshape(-1, 3)); Q.append(quads + off)
        off += ring.shape[0] * ring.shape[1]
    return np.concatenate(V), np.concatenate(COL), np.concatenate(Q)


def fib_dir(j, n):
    zz = 1 - 2 * (j + 0.5) / n
    rr = math.sqrt(max(0.0, 1 - zz * zz))
    return np.array([rr * math.cos(j * 2.39996), rr * math.sin(j * 2.39996), zz])


def build_foliage(tr):
    """Returns verts, faces (tris, quads), and per-vertex paint parameters."""
    V, TRI, QUAD = [], [], []
    TL, TC, TONE, CN = [], [], [], []
    off = 0
    px = tr.px

    def sub_for(r):
        return int(np.clip(math.ceil(math.log2(max(r * 1.05 / (4.2 * px), 1.0))), 2, 5))

    for cl in tr.clumps:
        rs = np.random.default_rng(cl["seed"])
        c, R, axes = cl["c"], cl["R"], cl["axes"]
        ez = math.sqrt(float(np.sum((axes[:, 2] * R) ** 2)))          # vertical half-extent
        # hierarchy: main mass -> satellites (sub-masses) -> tufts; every part is a lumpy ellipsoid
        parts = [(c, R, cl["seed"], None)]
        ns = cl["sat"]
        rot = frame_for(rs.normal(size=3))
        for j in range(ns):
            dloc = fib_dir(j, ns) @ rot
            sR = R * rs.uniform(*cl["sat_size"])
            sc = c + (dloc * R * cl["sat_out"]) @ axes
            dw = unit((dloc * R) @ axes)
            parts.append((sc, sR, cl["seed"] + 7 * (j + 1), 0.5 + 0.5 * dw[2]))
            n2 = cl["sub"]
            rot2 = frame_for(rs.normal(size=3))
            for j2 in range(n2):
                d2 = fib_dir(j2, n2) @ rot2
                d2w = unit((d2 * sR) @ axes)
                if float(np.dot(d2w, dw)) < -0.2:                      # buried inside the clump
                    continue
                parts.append((sc + (d2 * sR * 0.78) @ axes, sR * rs.uniform(0.36, 0.5),
                              cl["seed"] + 131 * (j + 1) + j2, 0.5 + 0.5 * (0.5 * dw[2] + 0.5 * d2w[2])))
        for pc, pR, seed, pup in parts:
            U, F = icosphere(sub_for(float(pR.mean())))
            disp = 1.0 + 0.085 * lump(U, seed, 2.3) + 0.04 * lump(U, seed + 1, 5.0)
            W = pc + (U * disp[:, None] * pR) @ axes
            V.append(W); TRI.append(F + off); off += len(W)
            own = 0.5 + 0.5 * unit_rows(W - pc)[:, 2]
            TL.append(own if pup is None else 0.5 * own + 0.5 * pup)
            TC.append(np.clip(0.5 + 0.5 * (W[:, 2] - c[2]) / (1.2 * ez), 0, 1))
            TONE.append(np.full(len(W), cl["tone"]))
            loc = ((W - c) @ axes.T) / (R * R)
            CN.append(unit_rows(loc @ axes))
    for pts, radii, tone in tr.plumes:
        k = sides_for(float(radii.max()), px)
        ph = tr.rng.uniform(0, 6.28, 3)

        def prof(th, s, t, ph=ph):
            return 1.0 + 0.12 * np.sin(2 * th + 5.0 * s + ph[0]) + 0.08 * np.sin(3 * th - 7.0 * s + ph[1])
        ring, radial, th, s, quads = tube_rings(pts, radii, k, prof)
        t = np.broadcast_to((s / s[-1])[:, None], radial.shape[:2])
        V.append(ring.reshape(-1, 3)); QUAD.append(quads + off); off += ring.shape[0] * ring.shape[1]
        TL.append((0.5 + 0.5 * radial[:, :, 2]).reshape(-1))
        TC.append((0.25 + 0.6 * t).reshape(-1))
        TONE.append(np.full(t.size, tone))
        tang = unit_rows(np.gradient(pts, axis=0))
        CN.append(unit_rows(radial + 0.35 * tang[:, None, :]).reshape(-1, 3))
    tris = np.concatenate(TRI) if TRI else np.zeros((0, 3), int)
    quads = np.concatenate(QUAD) if QUAD else np.zeros((0, 4), int)
    return (np.concatenate(V), tris, quads, np.concatenate(TL), np.concatenate(TC),
            np.concatenate(TONE), np.concatenate(CN))


def paint_foliage(tr, V, TL, TC, TONE, ell_c, ell_r):
    """Tone parameter 0..1 per vertex: dark undersides -> light, sky-facing tops."""
    th = np.clip(0.5 + 0.5 * (V[:, 2] - ell_c[2]) / ell_r[2], 0, 1)        # height in the crown
    t = np.clip(0.44 * TL + 0.34 * TC + 0.22 * th + TONE, 0, 1)
    return np.repeat(t[:, None], 3, axis=1)


def build_fruit(tr):
    if not tr.fruit:
        return None
    U, F = icosphere(2)
    V, COL, T = [], [], []
    for k, (p, r, c) in enumerate(tr.fruit):
        V.append(p + U * r)
        COL.append(np.tile(c, (len(U), 1)) * (0.8 + 0.4 * (U[:, 2:3] * 0.5 + 0.5)))
        T.append(F + k * len(U))
    return np.concatenate(V), np.concatenate(COL), np.concatenate(T)


def new_mesh(name, verts, tris=None, quads=None, smooth_shade=True):
    parts, totals = [], []
    for arr, n in ((tris, 3), (quads, 4)):
        if arr is not None and len(arr):
            parts.append(np.asarray(arr).reshape(-1))
            totals.append(np.full(len(arr), n))
    vertex_index = np.concatenate(parts)
    loop_total = np.concatenate(totals)
    me = bpy.data.meshes.new(name)
    me.vertices.add(len(verts))
    me.vertices.foreach_set("co", verts.astype(np.float32).ravel())
    me.loops.add(len(vertex_index))
    me.loops.foreach_set("vertex_index", vertex_index.astype(np.int32))
    me.polygons.add(len(loop_total))
    starts = np.concatenate([[0], np.cumsum(loop_total)[:-1]])
    me.polygons.foreach_set("loop_start", starts.astype(np.int32))
    me.polygons.foreach_set("loop_total", loop_total.astype(np.int32))
    me.polygons.foreach_set("use_smooth", np.full(len(loop_total), smooth_shade, dtype=bool))
    me.update(calc_edges=True)
    return me


def set_col(me, col):
    rgba = np.ones((len(col), 4), dtype=np.float32)
    rgba[:, :3] = col
    attr = me.color_attributes.new("Col", "FLOAT_COLOR", "POINT")
    attr.data.foreach_set("color", rgba.ravel())


def set_vec(me, name, vec):
    attr = me.attributes.new(name, "FLOAT_VECTOR", "POINT")
    attr.data.foreach_set("vector", vec.astype(np.float32).ravel())


